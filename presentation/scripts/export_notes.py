#!/usr/bin/env python3
"""Extract Quarto speaker notes into a printable HTML document."""
import json
from pathlib import Path
import shutil
import subprocess


ROOT = Path(__file__).resolve().parents[2]
PRESENTATION = ROOT / "presentation"
QUARTO = shutil.which("quarto") or str(ROOT / "build/tools/quarto/bin/quarto")


def pandoc(text, source, target):
    return subprocess.run(
        [QUARTO, "pandoc", "--from", source, "--to", target],
        input=text, text=True, capture_output=True, check=True,
    ).stdout


def nodes(value):
    if isinstance(value, dict):
        yield value
        for child in value.values():
            yield from nodes(child)
    elif isinstance(value, list):
        for child in value:
            yield from nodes(child)


def main():
    ast = json.loads(pandoc((PRESENTATION / "presentation.qmd").read_text(), "markdown", "json"))
    slides = [[]]
    for block in ast["blocks"]:
        if block["t"] == "HorizontalRule":
            slides.append([])
        elif block["t"] == "Header" and block["c"][0] <= 2:
            if slides[-1]:
                slides.append([])
            slides[-1].append(block)
        else:
            slides[-1].append(block)

    # Reveal.js generates a separate title slide when title metadata is present.
    first_number = 2 if "title" in ast["meta"] else 1
    output = []
    count = 0
    for number, blocks in enumerate(slides, first_number):
        notes = [n for n in nodes(blocks) if n.get("t") == "Div" and "notes" in n["c"][0][1]]
        if not notes:
            continue
        images = [Path(n["c"][2][0]).stem.replace("_", " ") for n in nodes(blocks) if n.get("t") == "Image"]
        label = " / ".join(dict.fromkeys(images))
        heading = f"Slide {number}" + (f" — {label}" if label else "")
        body = [b for note in notes for b in note["c"][1]]
        document = {"pandoc-api-version": ast["pandoc-api-version"], "meta": {}, "blocks": body}
        markdown = pandoc(json.dumps(document), "json", "markdown").strip()
        output.append(f"::: {{.slide-notes}}\n\n## {heading}\n\n{markdown}\n\n:::\n")
        count += 1

    header = '''---
title: "Presentation — speaker notes"
format:
  html:
    minimal: true
    embed-resources: true
    css: speaker-notes.css
    toc: false
    html-math-method: plain
---

<!-- Generated by scripts/export_notes.py. Edit notes in presentation.qmd. -->

'''
    target = PRESENTATION / "speaker-notes.qmd"
    target.write_text(header + "\n".join(output))
    subprocess.run([QUARTO, "render", str(target)], check=True, cwd=ROOT)
    print(f"Exported notes for {count} slides: {PRESENTATION / 'speaker-notes.html'}")


if __name__ == "__main__":
    main()
